"""Addon Lua export: one ForeverXP_Routes entry per route, plain table literals."""

HEADER = "-- AUTO-GENERATED by pipeline/export. DO NOT EDIT (ELLE DÜZENLEME)."


def _string(s: str) -> str:
    out = []
    for ch in s:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\r":
            out.append("\\r")
        elif ord(ch) < 0x20:
            out.append(f"\\{ord(ch):03d}")  # three digits so a following digit is not absorbed
        else:
            out.append(ch)
    return '"' + "".join(out) + '"'


def _scalar(value) -> str:
    if value is True:
        return "true"
    if value is False:
        return "false"
    if isinstance(value, int):
        return str(value)
    if isinstance(value, float):
        if value != value or value in (float("inf"), float("-inf")):
            raise ValueError(f"cannot write {value!r} as a Lua number")
        return repr(value)
    if isinstance(value, str):
        return _string(value)
    raise ValueError(f"cannot write {type(value).__name__} as a Lua value")


def _items(value: dict):
    return [(k, value[k]) for k in sorted(value, key=str) if value[k] is not None]


def _inline(value) -> str:
    if isinstance(value, (list, tuple)):
        if any(v is None for v in value):
            raise ValueError("None inside a list cannot be written as a Lua sequence")
        return "{" + ", ".join(_inline(v) for v in value) + "}"
    if isinstance(value, dict):
        return "{" + ", ".join(f"[{_string(str(k))}]={_inline(v)}" for k, v in _items(value)) + "}"
    return _scalar(value)


def _pretty(value, level: int) -> str:
    """Dicts one key per line; lists of tables one element per line (dict elements inline); scalar lists inline."""
    pad, inner = "  " * level, "  " * (level + 1)
    if isinstance(value, dict):
        items = _items(value)
        if not items:
            return "{}"
        lines = [f"{inner}[{_string(str(k))}] = {_pretty(v, level + 1)}," for k, v in items]
        return "{\n" + "\n".join(lines) + "\n" + pad + "}"
    if isinstance(value, (list, tuple)):
        if any(v is None for v in value):
            raise ValueError("None inside a list cannot be written as a Lua sequence")
        if not any(isinstance(v, (dict, list, tuple)) for v in value):
            return _inline(value)
        lines = [inner + (_inline(v) if isinstance(v, dict) else _pretty(v, level + 1)) + "," for v in value]
        return "{\n" + "\n".join(lines) + "\n" + pad + "}"
    return _scalar(value)


def to_lua(route: dict) -> str:
    """The Lua data file text: header, registry line and the indented route table."""
    return "\n".join(
        [
            HEADER,
            "ForeverXP_Routes = ForeverXP_Routes or {}",
            f"ForeverXP_Routes[{_string(route['id'])}] = {_pretty(route, 0)}",
            "",
        ]
    )
